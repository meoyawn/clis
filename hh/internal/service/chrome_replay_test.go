type chromeExchange struct {
	Request struct {
		Method  string            `json:"method"`
		Path    string            `json:"path"`
		Headers map[string]string `json:"headers"`
		Body    string            `json:"body"`
	} `json:"request"`
	Input    map[string]string `json:"input"`
	Response struct {
		Status int             `json:"status"`
		Body   json.RawMessage `json:"body"`
	} `json:"response"`
}

func TestChromeApplicationWireReplay(t *testing.T) {
	for _, name := range []string{"initial", "after-captcha"} {
		t.Run(name, func(t *testing.T) {
			exchange := loadChromeExchange(t, name)
			var calls atomic.Int32
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, request *http.Request) {
				calls.Add(1)
				assertChromeRequest(t, request, exchange)
				w.Header().Set("Content-Type", "application/json")
				w.WriteHeader(exchange.Response.Status)
				_, _ = w.Write(exchange.Response.Body)
			}))
			defer server.Close()
			base, _ := url.Parse(server.URL)
			jar, _ := cookiejar.New(nil)
			jar.SetCookies(base, []*http.Cookie{{Name: "_xsrf", Value: "fixture-token"}})
			headers := make(http.Header)
			for key, value := range exchange.Request.Headers {
				if key != "content-type" && key != "x-xsrftoken" && key != "origin" {
					headers.Set(key, strings.ReplaceAll(value, "https://hh.ru", base.String()))
				}
			}
			client := NewClient(browserHTTPClient(base, jar, server.Client().Transport), base, headers)
			fields := make(Object, len(exchange.Input))
			for key, value := range exchange.Input {
				fields[key] = value
			}
			// CAPTCHA proof is supplied by the human in the recording, never
			// generated by this codec; no challenge-solving or retry occurs.
			fields["letter"] = strings.ReplaceAll(exchange.Input["letter"], "\r\n", "\n")
			body, err := client.postApplicationForm(context.Background(), fields)
			if exchange.Response.Status == 403 {
				var diagnostic *HTTPError
				if !errors.As(err, &diagnostic) || diagnostic.Status != 403 || strings.Contains(err.Error(), "fixture-captcha-state") {
					t.Fatalf("CAPTCHA must stop with a redacted diagnostic: %v", err)
				}
			} else if err != nil || !bytes.Equal(body, exchange.Response.Body) {
				t.Fatalf("recorded response was not returned intact: body=%s err=%v", body, err)
			}
			if calls.Load() != 1 {
				t.Fatalf("expected exactly one request, got %d", calls.Load())
			}
		})
	}
}

func loadChromeExchange(t *testing.T, name string) chromeExchange {
	t.Helper()
	data, err := os.ReadFile("testdata/chrome/submission-" + name + ".json")
	if err != nil {
		t.Fatal(err)
	}
	var exchange chromeExchange
	if err := json.Unmarshal(data, &exchange); err != nil {
		t.Fatal(err)
	}
	return exchange
}

func assertChromeRequest(t *testing.T, request *http.Request, exchange chromeExchange) {
	t.Helper()
	body, err := io.ReadAll(request.Body)
	if err != nil {
		t.Error(err)
		return
	}
	if request.Method != exchange.Request.Method || request.URL.RequestURI() != exchange.Request.Path {
		t.Errorf("request differs from Chrome: %s %s", request.Method, request.URL.RequestURI())
	}
	_, actual, err := mime.ParseMediaType(request.Header.Get("Content-Type"))
	if err != nil {
		t.Error(err)
		return
	}
	_, recorded, err := mime.ParseMediaType(exchange.Request.Headers["content-type"])
	if err != nil {
		t.Error(err)
		return
	}
	// Substitute only boundary entropy and the local test origin. Every other
	// multipart byte and application header must equal the Chrome recording.
	boundary := actual["boundary"]
	normalized := bytes.ReplaceAll(body, []byte(boundary), []byte(recorded["boundary"]))
	if !bytes.Equal(normalized, []byte(exchange.Request.Body)) {
		t.Errorf("multipart body differs from anonymized Chrome recording:\n%s", normalized)
	}
	suffix := strings.TrimPrefix(boundary, "----WebKitFormBoundary")
	if !strings.HasPrefix(boundary, "----WebKitFormBoundary") || len(suffix) != 16 || strings.Trim(suffix, "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789") != "" || suffix == strings.Repeat("A", 16) {
		t.Errorf("multipart boundary does not use fresh Chrome-format entropy: %q", boundary)
	}
	got := request.Header.Clone()
	// Compression and HTTP/2 framing are transport concerns; application
	// metadata must match in full. There is no blanket header allowlist here.
	if got.Get("Accept-Encoding") != "gzip" {
		t.Errorf("unexpected transport compression header: %q", got.Get("Accept-Encoding"))
	}
	got.Del("Accept-Encoding")
	if request.ContentLength != int64(len(body)) || len(request.TransferEncoding) != 0 {
		t.Error("multipart request must have a fixed Content-Length")
	}
	if value := got.Get("Content-Length"); value != "" && value != strconv.Itoa(len(body)) {
		t.Errorf("wrong Content-Length: %s", value)
	}
	got.Del("Content-Length")
	got.Set("Content-Type", strings.ReplaceAll(got.Get("Content-Type"), boundary, recorded["boundary"]))
	want := make(http.Header)
	for name, value := range exchange.Request.Headers {
		want.Set(name, strings.ReplaceAll(value, "https://hh.ru", "http://"+request.Host))
	}
	want.Set("Cookie", "_xsrf=fixture-token")
	if !reflect.DeepEqual(got, want) {
		t.Errorf("headers differ from Chrome contract:\ngot: %v\nwant: %v", got, want)
	}
}
